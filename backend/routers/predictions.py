"""
KSHETRA: Prediction-persistence router (Step 3C of the persistence plan).

Calls the SAME reusable inference function /predict uses
(inference_service.run_prediction — Step 3A) and stores the result as an
append-only row in `predictions` (Step 1's table/model, UNMODIFIED — no
migration, no new table). Deliberately exposes no PATCH/DELETE: predictions
are historical inference events, never edited or removed (see
schemas.py — there is no PredictionUpdate schema, on purpose).

Mounted in backend/main.py alongside the Step 2 CRUD routers, guarded by the
same _PERSISTENCE_IMPORT_ERROR fallback — if the database layer is
unavailable, these routes are simply not mounted. /predict itself never
imports this module and has zero dependency on it or on the database.
"""

from __future__ import annotations

from typing import Any, Dict, List, Optional

from fastapi import APIRouter, Depends, HTTPException, status
from sqlalchemy.orm import Session

import crud
import models
import schemas
from database import get_db
from inference_service import CaseInput, run_prediction

router = APIRouter(tags=["predictions"])


class PredictionRequest(CaseInput):
    """
    The exact same 7 fields /predict accepts — inherited from CaseInput, so
    the bounds (ge/le) and the acquisition_stage validator are reused
    verbatim, never re-implemented — plus one addition: an optional
    `parcel_id` for a parcel-scoped prediction (see POST_PREDICTION_FLOW in
    the Step 3 task).
    """

    parcel_id: Optional[str] = None


# Text stored in Prediction columns the raw ML pipeline does not produce at
# all (predict.py / explain.py / survival.py / demo_fallback.py — none of
# them output a "recommended action" or a probability->calendar conversion;
# see the Step 3 report's "schema problem" section for why). These are
# explicit, honest "not available" notices — NOT a fabricated recommendation
# or a fabricated delay estimate — matching the project's existing pattern of
# saying so directly (e.g. survival.py's own `remaining_time_note`) rather
# than inventing a plausible-looking number or sentence.
_NO_DELAY_RANGE_TEXT = (
    "Not derived by this inference pipeline (probability-only model output; "
    "no calendar/month synthesis is performed by this endpoint)."
)
_NO_RECOMMENDED_ACTION_TEXT = (
    "Not generated by this inference pipeline (no recommended-action synthesis "
    "exists in predict.py / explain.py / survival.py / demo_fallback.py)."
)


def _build_prediction_row(
    *,
    project_id: str,
    project_name: str,
    parcel_id: Optional[str],
    case_dict: Dict[str, Any],
    result: Dict[str, Any],
) -> models.Prediction:
    """
    Maps the raw run_prediction() output — the EXACT dict /predict returns,
    untouched — onto the Prediction ORM model (Step 1, unmodified schema).
    Every field below is either:
      (a) a direct passthrough of a real model/pipeline output,
      (b) a lossless format normalization (documented inline), or
      (c) one of the two explicit unavailable-notices above.
    Nothing here is a fabricated prediction value.
    """
    classification = result["classification"]
    explainability = result["explainability"]
    survival_analysis = result.get("survival_analysis")
    meta = result["meta"]

    human_readable_drivers = explainability.get("human_readable_drivers") or []
    # predict.py / demo_fallback.py both guarantee at least one entry (they
    # append a "Normal operational parameters..." string when nothing else
    # qualifies), so this fallback string is a defensive belt-and-suspenders
    # only — it is not expected to be hit in practice.
    top_risk_factor = human_readable_drivers[0] if human_readable_drivers else "No driver information available."

    return models.Prediction(
        project_id=project_id,
        parcel_id=parcel_id,
        scope="parcel" if parcel_id else "project",
        project_name=project_name,
        generated_at=meta["generated_at"],
        # True: this is a direct in-process call to run_prediction() that
        # returned a result — live-model AND demo-fallback both count as a
        # successful backend response (matches the frontend's existing
        # isRealApiPrediction semantic, which is false only when the call
        # itself fails outright — see src/context/AppContext.tsx, read-only,
        # not modified). There is no network layer in this code path that
        # could fail the way a browser fetch could, so this is never False
        # for this endpoint.
        is_real_api_prediction=True,
        prediction_mode=meta["mode"],
        api_error=None,
        model_input=case_dict,
        sample_coverage=None,  # frontend-only aggregation concept; not computed by this endpoint
        input_diagnostics=meta.get("input_diagnostics"),
        aggregation_notes=[
            "Persisted via the Step 3 prediction-persistence endpoint: model_input "
            "is the request payload as sent, not aggregated from stored parcel records."
        ],
        delay_probability=classification["delay_probability"],
        delay_risk_score=classification["risk_score"],
        # Normalized from the model's uppercase risk_tier ("HIGH"/"MEDIUM"/"LOW")
        # to lowercase to match this column's documented RiskLevel convention
        # ('low'|'medium'|'high', see models.py) — a lossless casing change,
        # not a new or different value.
        risk_level=classification["risk_tier"].lower(),
        # Never available from a probability-only classifier — matches the
        # project's own established rule against fabricating a months figure
        # from a probability (see memory: predictedDelayMonths fabrication
        # removal). NULL, not invented.
        predicted_delay_months=None,
        predicted_delay_range=_NO_DELAY_RANGE_TEXT,
        top_risk_factor=top_risk_factor,
        ai_explanation=classification["status_label"],
        shap_factors=explainability.get("top_risk_drivers") or [],
        survival_analysis=survival_analysis,
        recommended_action=_NO_RECOMMENDED_ACTION_TEXT,
        # STEP 9B: verbatim passthrough of inference_service.run_prediction()'s
        # meta.model_version (None for demo-fallback, or when the loaded
        # LightGBM artifact metadata never carried a version string).
        model_version=meta.get("model_version"),
    )


@router.post(
    "/api/projects/{project_id}/predictions",
    response_model=schemas.PredictionRead,
    status_code=status.HTTP_201_CREATED,
)
def create_project_prediction(project_id: str, payload: PredictionRequest, db: Session = Depends(get_db)):
    project = crud.get_project(db, project_id)
    if project is None:
        raise HTTPException(status_code=status.HTTP_404_NOT_FOUND, detail=f"Project '{project_id}' not found.")

    if payload.parcel_id is not None:
        parcel = crud.get_parcel(db, payload.parcel_id)
        if parcel is None:
            raise HTTPException(
                status_code=status.HTTP_404_NOT_FOUND,
                detail=f"Parcel '{payload.parcel_id}' not found.",
            )
        if parcel.project_id != project_id:
            raise HTTPException(
                status_code=status.HTTP_400_BAD_REQUEST,
                detail=(
                    f"Parcel '{payload.parcel_id}' belongs to project '{parcel.project_id}', "
                    f"not '{project_id}'. Refusing to associate it with the wrong project."
                ),
            )

    # Same 7-field dict shape /predict's payload.model_dump() produces —
    # parcel_id is this router's own addition, excluded before inference.
    case_dict = payload.model_dump(exclude={"parcel_id"})

    # THE call: identical function, identical input shape, that /predict uses.
    result = run_prediction(case_dict)

    row = _build_prediction_row(
        project_id=project_id,
        project_name=project.name,
        parcel_id=payload.parcel_id,
        case_dict=case_dict,
        result=result,
    )
    return crud.create_prediction(db, row)


@router.get("/api/projects/{project_id}/predictions", response_model=List[schemas.PredictionRead])
def list_project_predictions(project_id: str, db: Session = Depends(get_db)):
    if crud.get_project(db, project_id) is None:
        raise HTTPException(status_code=status.HTTP_404_NOT_FOUND, detail=f"Project '{project_id}' not found.")
    return crud.list_project_predictions(db, project_id)


@router.get("/api/projects/{project_id}/predictions/latest", response_model=schemas.PredictionRead)
def latest_project_prediction(project_id: str, db: Session = Depends(get_db)):
    if crud.get_project(db, project_id) is None:
        raise HTTPException(status_code=status.HTTP_404_NOT_FOUND, detail=f"Project '{project_id}' not found.")
    obj = crud.latest_project_prediction(db, project_id)
    if obj is None:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail=f"No predictions exist yet for project '{project_id}'.",
        )
    return obj


